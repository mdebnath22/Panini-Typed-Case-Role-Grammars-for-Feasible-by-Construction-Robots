"""
Neural Φ : JEPA-Style Bidirectional Rule↔Motion Mapping
=======================================================

Architecture mirrors the JEPA-as-optimizer design (context encoder ->
latent predictor -> decoder, EMA target encoder, latent-space prediction
loss), but the tokens are *applied sūtras* instead of (θ, r) pairs and the
decoded object is a twist ξ ∈ se(3) per rule instead of a policy vector.

Forward direction  Φ  : rule-sequence tokens -> twist sequence
Inverse direction  Φ⁻¹: twist sequence -> rule-type logits (symbolic readout)

Initialization from the closed-form seed: training data is generated by
PhiSeed on randomized scenes, so the network warm-starts by distilling the
seed correspondence, then can be fine-tuned on demonstration trajectories.
"""

from __future__ import annotations

import copy
from typing import Dict, List, Sequence, Tuple

import numpy as np
import torch
import torch.nn as nn

from ptg.karaka import Karaka
from ptg.sutra import AppliedRule

TRANSFORMS = ["APPROACH", "APPROACH_SIDE", "GRASP", "LIFT", "TRANSPORT",
              "PLACE", "ROTATE_TOOL", "RETRACT"]
T2I = {t: i for i, t in enumerate(TRANSFORMS)}
ROLES = list(Karaka)
PARAM_KEYS = ["approach_height", "lateral_offset", "grasp_depth",
              "lift_height", "release_height", "rotation_angle"]

TOKEN_DIM = len(TRANSFORMS) + 3 * len(ROLES) + len(PARAM_KEYS) + 1  # +vibhāṣā


def tokenize(applied: AppliedRule) -> np.ndarray:
    """Encode one applied rule: transformation one-hot ⊕ per-role (present
    flag is folded into position vector; absent roles are zeroed) ⊕ params
    ⊕ vibhāṣā flag."""
    v = np.zeros(TOKEN_DIM, dtype=np.float32)
    v[T2I[applied.sutra.transformation]] = 1.0
    off = len(TRANSFORMS)
    for j, role in enumerate(ROLES):
        ent = applied.frame.get(role)
        if ent is not None:
            v[off + 3 * j: off + 3 * j + 3] = ent.position
    off += 3 * len(ROLES)
    for k, key in enumerate(PARAM_KEYS):
        v[off + k] = applied.params.get(key, 0.0)
    v[-1] = float(applied.sutra.vibhasa)
    return v


def tokenize_sequence(derivation: Sequence[AppliedRule],
                      ee_init: np.ndarray) -> np.ndarray:
    toks = np.stack([tokenize(a) for a in derivation])
    # prepend end-effector start position to every token (context grounding)
    ee = np.tile(ee_init[:3, 3].astype(np.float32), (len(toks), 1))
    return np.concatenate([toks, ee], axis=1)  # (L, TOKEN_DIM + 3)


class PhiNeural(nn.Module):
    def __init__(self, d_model: int = 128, n_heads: int = 4,
                 n_layers: int = 2, max_len: int = 16):
        super().__init__()
        in_dim = TOKEN_DIM + 3
        self.in_proj = nn.Linear(in_dim, d_model)
        self.pos = nn.Parameter(torch.zeros(1, max_len, d_model))
        enc_layer = nn.TransformerEncoderLayer(
            d_model, n_heads, dim_feedforward=4 * d_model,
            batch_first=True, dropout=0.0)
        self.encoder = nn.TransformerEncoder(enc_layer, n_layers)
        # JEPA predictor: predicts latent of the *next* rule token
        self.predictor = nn.Sequential(
            nn.Linear(d_model, 2 * d_model), nn.GELU(),
            nn.Linear(2 * d_model, d_model))
        # decoder: latent -> twist (Φ direction)
        self.decoder = nn.Sequential(
            nn.Linear(d_model, 2 * d_model), nn.GELU(),
            nn.Linear(2 * d_model, 6))
        # inverse readout: latent -> rule-type logits (Φ⁻¹ direction)
        self.inv_head = nn.Linear(d_model, len(TRANSFORMS))
        # EMA target encoder
        self.target_encoder = copy.deepcopy(
            nn.ModuleDict({"in_proj": self.in_proj, "enc": self.encoder}))
        for p in self.target_encoder.parameters():
            p.requires_grad_(False)
        self.ema_tau = 0.99

    def encode(self, x: torch.Tensor) -> torch.Tensor:
        h = self.in_proj(x) + self.pos[:, : x.shape[1]]
        mask = nn.Transformer.generate_square_subsequent_mask(
            x.shape[1], device=x.device)
        return self.encoder(h, mask=mask, is_causal=True)

    @torch.no_grad()
    def encode_target(self, x: torch.Tensor) -> torch.Tensor:
        h = self.target_encoder["in_proj"](x) + self.pos[:, : x.shape[1]]
        mask = nn.Transformer.generate_square_subsequent_mask(
            x.shape[1], device=x.device)
        return self.target_encoder["enc"](h, mask=mask, is_causal=True)

    @torch.no_grad()
    def ema_update(self):
        for p, tp in zip(
                list(self.in_proj.parameters()) + list(self.encoder.parameters()),
                list(self.target_encoder["in_proj"].parameters())
                + list(self.target_encoder["enc"].parameters())):
            tp.mul_(self.ema_tau).add_((1 - self.ema_tau) * p)

    def forward(self, x: torch.Tensor) -> Dict[str, torch.Tensor]:
        z = self.encode(x)                       # (B, L, d)
        return {
            "latent": z,
            "twists": self.decoder(z),           # Φ:  per-rule twist
            "pred_next": self.predictor(z),      # JEPA next-latent prediction
            "rule_logits": self.inv_head(z),     # Φ⁻¹: symbolic readout
        }


def jepa_phi_loss(model: PhiNeural, x: torch.Tensor, xi_true: torch.Tensor,
                  rule_ids: torch.Tensor, w_jepa: float = 1.0,
                  w_twist: float = 10.0, w_inv: float = 1.0
                  ) -> Tuple[torch.Tensor, Dict[str, float]]:
    out = model(x)
    # latent-space JEPA loss: predict target latent of token t+1 from token t
    with torch.no_grad():
        z_tgt = model.encode_target(x)
    l_jepa = ((out["pred_next"][:, :-1] - z_tgt[:, 1:].detach()) ** 2).mean()
    l_twist = ((out["twists"] - xi_true) ** 2).mean()
    l_inv = nn.functional.cross_entropy(
        out["rule_logits"].reshape(-1, len(TRANSFORMS)), rule_ids.reshape(-1))
    loss = w_jepa * l_jepa + w_twist * l_twist + w_inv * l_inv
    return loss, {"jepa": l_jepa.item(), "twist": l_twist.item(),
                  "inv": l_inv.item()}
